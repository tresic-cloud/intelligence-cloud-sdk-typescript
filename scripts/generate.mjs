// Generates src/generated/openapi.ts (types) and src/generated/spec.ts (operation table,
// query-parameter rules and response shapes used for projection) from openapi.yaml.
//
// Usage: node scripts/generate.mjs [path/to/openapi.yaml]
// Default spec path: ../../openapi.yaml (the copy published next to the SDK folders).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import YAML from "yaml";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const specPath = resolve(process.argv[2] ?? resolve(root, "../../openapi.yaml"));
const doc = YAML.parse(readFileSync(specPath, "utf8"));

// ---------------------------------------------------------------- types
const ast = await openapiTS(pathToFileURL(specPath));
const banner = "// Generated by scripts/generate.mjs from openapi.yaml. Do not edit.\n/* eslint-disable */\n";
writeFileSync(resolve(root, "src/generated/openapi.ts"), banner + astToString(ast));

// ---------------------------------------------------------------- helpers
function deref(s) {
  let guard = 0;
  while (s && s.$ref) {
    const parts = s.$ref.replace(/^#\//, "").split("/");
    s = parts.reduce((o, k) => o[k], doc);
    if (++guard > 50) throw new Error("ref loop");
  }
  return s;
}

function types(s) {
  if (!s.type) return [];
  return Array.isArray(s.type) ? s.type : [s.type];
}

// Shape grammar: "v" = scalar, "*" = keep anything, {o:{k:shape}} = object, {a:shape} = array.
function shape(s0, depth = 0) {
  const s = deref(s0);
  if (!s || depth > 40) return "*";
  const alts = s.oneOf ?? s.anyOf;
  if (alts) return mergeShapes(alts.map((a) => shape(a, depth + 1)));
  if (s.allOf) return mergeShapes(s.allOf.map((a) => shape(a, depth + 1)));
  const t = types(s);
  if (t.includes("array") || s.items) return { a: s.items ? shape(s.items, depth + 1) : "*" };
  if (t.includes("object") || s.properties) {
    if (s.additionalProperties === true || !s.properties) return "*";
    const o = {};
    for (const [k, v] of Object.entries(s.properties)) o[k] = shape(v, depth + 1);
    return { o };
  }
  if (t.length === 0 && !s.enum && s.const === undefined) return "*";
  return "v";
}

function mergeShapes(list) {
  if (list.includes("*")) return "*";
  const objs = list.filter((x) => typeof x === "object" && x.o);
  const arrs = list.filter((x) => typeof x === "object" && x.a);
  if (objs.length && !arrs.length) {
    const o = {};
    for (const s of objs) for (const [k, v] of Object.entries(s.o)) o[k] = k in o ? mergeShapes([o[k], v]) : v;
    // a scalar alternative next to an object means "object or scalar": keep the object rules
    return { o };
  }
  if (arrs.length && !objs.length) return { a: mergeShapes(arrs.map((x) => x.a)) };
  if (objs.length && arrs.length) return "*";
  return "v";
}

function param(p) {
  const d = deref(p);
  const s = deref(d.schema ?? {});
  const t = types(s)[0] ?? "string";
  const out = { name: d.name, in: d.in, type: t };
  if (d.required) out.required = true;
  if (s.enum) out.enum = s.enum;
  if (s.format) out.format = s.format;
  if (s.minimum !== undefined) out.minimum = s.minimum;
  if (s.maximum !== undefined) out.maximum = s.maximum;
  if (s.minLength !== undefined) out.minLength = s.minLength;
  if (s.maxItems !== undefined) out.maxItems = s.maxItems;
  if (t === "array") {
    const it = deref(s.items ?? {});
    out.items = { type: types(it)[0] ?? "string" };
    if (it.format) out.items.format = it.format;
    if (it.pattern) out.items.pattern = it.pattern;
    if (it.enum) out.items.enum = it.enum;
  }
  return out;
}

// ---------------------------------------------------------------- operations
const operations = {};
for (const [path, item] of Object.entries(doc.paths)) {
  const shared = item.parameters ?? [];
  for (const method of ["get", "post", "put", "patch", "delete"]) {
    const op = item[method];
    if (!op) continue;
    const params = [...shared, ...(op.parameters ?? [])].map(param);
    const success = Object.entries(op.responses ?? {})
      .filter(([code]) => /^2/.test(code))
      .map(([, r]) => deref(r))
      .map((r) => r?.content?.["application/json"]?.schema)
      .filter(Boolean)
      .map((s) => shape(s));
    operations[op.operationId] = {
      method: method.toUpperCase(),
      path,
      tag: op.tags?.[0] ?? "",
      role: op["x-required-role"] ?? null,
      query: params.filter((p) => p.in === "query"),
      pathParams: params.filter((p) => p.in === "path").map((p) => p.name),
      headers: params.filter((p) => p.in === "header").map((p) => p.name),
      hasBody: Boolean(op.requestBody),
      bodyRequired: Boolean(op.requestBody?.required),
      response: success.length ? mergeShapes(success) : null,
      summary: op.summary ?? "",
    };
  }
}

const webhookShapes = {};
for (const [name, item] of Object.entries(doc.webhooks ?? {})) {
  const s = item.post?.requestBody?.content?.["application/json"]?.schema;
  if (s) webhookShapes[name] = shape(s);
}

const out = `// Generated by scripts/generate.mjs from openapi.yaml. Do not edit.
/* eslint-disable */
import type { OperationTable, Shape } from "../spec-types.js";

export const OPERATIONS = ${JSON.stringify(operations)} as const satisfies OperationTable;

export type OperationId = keyof typeof OPERATIONS;

export const WEBHOOK_SHAPES: Record<string, Shape> = ${JSON.stringify(webhookShapes)};
`;
writeFileSync(resolve(root, "src/generated/spec.ts"), out);

// ---------------------------------------------------------------- low-level resource wrappers
const NAMESPACES = {
  Resellers: "resellers", Companies: "companies", "Single sign-on": "sso", Products: "products",
  Locations: "locations", "User groups": "groups", Connectors: "connectors", "First Alert": "firstAlert",
  "Insights Hub": "insightsHub", Users: "users", "After Call settings": "afterCallSettings",
  Account: "account", Calls: "calls", Alerts: "alerts", Tasks: "tasks", Insights: "insights",
  "Events and webhooks": "webhooks",
};
const byNs = {};
for (const [id, op] of Object.entries(operations)) {
  const ns = NAMESPACES[op.tag];
  if (!ns) continue; // Authentication is handled by the client itself
  (byNs[ns] ??= []).push([id, op]);
}
const lines = [
  "// Generated by scripts/generate.mjs from openapi.yaml. Do not edit.",
  "/* eslint-disable */",
  'import type { Core, QueryOf, BodyOf, ResponseOf, ItemOf, Page } from "../core.js";',
  "",
];
const nsTypes = [];
for (const [ns, ops] of Object.entries(byNs)) {
  const fn = "make" + ns[0].toUpperCase() + ns.slice(1);
  lines.push(`export function ${fn}(c: Core) {`, "  return {");
  for (const [id, op] of ops) {
    const pathArgs = op.pathParams.map((p) => `${p}: string`);
    const args = [...pathArgs];
    if (op.hasBody) args.push(`body: BodyOf<"${id}">`);
    if (op.query.length) args.push(`query: QueryOf<"${id}"> = {}`);
    const pathList = `[${op.pathParams.join(", ")}]`;
    const opts = [op.hasBody ? "body" : null, op.query.length ? "query" : null].filter(Boolean).join(", ");
    const paged = id.startsWith("list") && op.query.some((q) => q.name === "cursor");
    const summary = (op.summary || id).replace(/\*\//g, "");
    lines.push(`    /** ${summary}. \`${op.method} ${op.path}\`${paged ? ". One page: rows (unwrapped) in \`items\`." : ""} */`);
    if (paged) {
      lines.push(`    ${id}: (${args.join(", ")}): Promise<Page<ItemOf<"${id}">, ResponseOf<"${id}">>> => c.page("${id}", ${pathList}, { ${opts} }),`);
    } else {
      lines.push(`    ${id}: (${args.join(", ")}): Promise<ResponseOf<"${id}">> => c.call("${id}", ${pathList}, { ${opts} }),`);
    }
    if (paged) {
      const it = "iter" + id.slice(4);
      const iargs = [...pathArgs, `query: Omit<QueryOf<"${id}">, "cursor"> & { maxItems?: number } = {}`];
      lines.push(`    /** Every row of \`${op.method} ${op.path}\`, following cursors with limit=100. */`);
      lines.push(`    ${it}: (${iargs.join(", ")}): AsyncGenerator<ItemOf<"${id}">> => c.iterate("${id}", ${pathList}, query),`);
    }
  }
  lines.push("  };", "}", "");
  nsTypes.push([ns, fn]);
}
lines.push("export const RESOURCE_FACTORIES = {");
for (const [ns, fn] of nsTypes) lines.push(`  ${ns}: ${fn},`);
lines.push("} as const;", "");
writeFileSync(resolve(root, "src/generated/resources.ts"), lines.join("\n"));
console.log(`generated ${Object.keys(operations).length} operations, ${Object.keys(webhookShapes).length} webhooks from ${specPath}`);
